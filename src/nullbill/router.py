"""Router guest files: interfaces, nftables, dnsmasq.

The router is a Debian VM with one leg in every planned zone and an uplink
on the LAN bridge. nftables repeats the flow list as a second guard behind
pve-firewall. dnsmasq runs twice: zones with direct egress may resolve
public names; proxy and no-egress zones get internal names only, so DNS
cannot carry data out of them.
"""

from nullbill.flows import HOST, PRIVATE, mac, resolve_flows
from nullbill.render import strip_notes

HEADER = "# Generated by nullbill. Do not edit; change config.yaml and re-run apply.\n"
UPLINK = "nb-uplink"


def _iface(zone: str) -> str:
    return f"nb-{zone}"[:15]  # Linux interface names are at most 15 bytes


def _links(plan: dict, model: dict) -> dict[str, str]:
    files = {}
    legs = [(UPLINK, mac(0, 1))] + [(_iface(z), mac(model["zones"][z]["index"], 1)) for z in plan["zones"]]
    for i, (name, address) in enumerate(legs):
        files[f"etc/systemd/network/{10 + i}-{name}.link"] = HEADER + f"[Match]\nMACAddress={address}\n\n[Link]\nName={name}\n"
    return files


def _interfaces(plan: dict) -> str:
    out = [HEADER, "auto lo\niface lo inet loopback\n\n", f"auto {UPLINK}\niface {UPLINK} inet dhcp\n"]
    for zone, z in plan["zones"].items():
        prefix = z["subnet"].split("/")[1]
        out.append(f"\nauto {_iface(zone)}\niface {_iface(zone)} inet static\n    address {z['gateway']}/{prefix}\n")
    return "".join(out)


def _set(cidrs) -> str:
    return "{ " + ", ".join(cidrs) + " }"


def _nftables(plan: dict, model: dict) -> str:
    zones = plan["zones"]
    pool_zones = sorted({g["zone"] for g in plan["guests"].values() if g["kind"] == "vm-pool"})
    flows = resolve_flows(plan, model)
    lines = [
        HEADER,
        "flush ruleset\n\n",
        "table inet nullbill {\n",
        f"    set private {{\n        type ipv4_addr\n        flags interval\n        elements = {_set(PRIVATE)}\n    }}\n\n",
        "    chain input {\n        type filter hook input priority filter; policy drop;\n",
        "        ct state established,related accept\n        ct state invalid drop\n        iif lo accept\n",
    ]
    if pool_zones:
        pools = ", ".join(f'"{_iface(z)}"' for z in pool_zones)
        lines.append(f"        iifname {{ {pools} }} udp dport 67 accept # DHCP for pool clones\n")
    for flow in flows:
        if flow.dest == "router":
            lines.append(f"        ip saddr {_set(flow.source_cidrs)} {flow.proto} dport {flow.port} accept # {flow.ref}\n")
    lines += [
        "    }\n\n",
        "    chain forward {\n        type filter hook forward priority filter; policy drop;\n",
        "        ct state established,related accept\n        ct state invalid drop\n",
    ]
    seen = set()
    for flow in flows:
        if flow.dest == "router":
            continue
        rule = f"ip saddr {_set(flow.source_cidrs)} ip daddr {_set(flow.dest_cidrs)} {flow.proto} dport {flow.port} accept"
        if rule in seen:
            continue
        seen.add(rule)
        label = "the PVE host" if flow.dest == HOST else flow.dest
        lines.append(f"        {rule} # {flow.ref} to {label}\n")
    for zone, z in zones.items():
        if z["egress"] == "direct":
            lines.append(f'        iifname "{_iface(zone)}" oifname "{UPLINK}" ip daddr != @private accept # direct egress\n')
    lines += [
        "    }\n}\n\n",
        "table ip nullbill-nat {\n    chain postrouting {\n        type nat hook postrouting priority srcnat; policy accept;\n",
        f'        oifname "{UPLINK}" masquerade\n    }}\n}}\n',
    ]
    return "".join(lines)


def _dnsmasq(plan: dict, model: dict, zones: list[str], external: bool) -> str:
    domain = model["network"]["domain"]
    # except-interface=lo: both instances would otherwise claim 127.0.0.1:53.
    lines = [HEADER, "bind-interfaces\nexcept-interface=lo\n", "domain-needed\nbogus-priv\n", f"local=/{domain}/\ndomain={domain}\n"]
    lines += [f"interface={_iface(z)}\n" for z in zones]
    if not external:
        lines.append("# Internal names only: nothing here forwards upstream.\nno-resolv\n")
    for name, guest in plan["guests"].items():
        if "ip" in guest:
            lines.append(f"host-record={name}.{domain},{guest['ip']}\n")
    lines.append(f"host-record=router.{domain},{plan['zones']['mgmt']['gateway']}\n")
    lines.append(f"host-record=pve.{domain},{plan['zones']['mgmt']['host_ip']}\n")
    for name, guest in plan["guests"].items():
        if guest["kind"] == "vm-pool" and guest["zone"] in zones:
            subnet = plan["zones"][guest["zone"]]["subnet"]
            base = subnet.rsplit(".", 1)[0]
            lines.append(f"dhcp-range={base}.130,{base}.190,255.255.255.0,1h # {name} clones\n")
            template_mac = mac(model["zones"][guest["zone"]]["index"], model["services"][name]["id"])
            lines.append(f"dhcp-host={template_mac},{guest['template_ip']} # {name} golden image\n")
    return "".join(lines)


DNSMASQ_UNIT = (
    HEADER
    + """[Unit]
Description=NullBill dnsmasq (%i)
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=/usr/sbin/dnsmasq --keep-in-foreground --conf-file=/etc/nullbill/dnsmasq-%i.conf
Restart=on-failure

[Install]
WantedBy=multi-user.target
"""
)


def render_router(plan_with_notes: dict, model: dict) -> dict[str, str]:
    """Return {path on the router: content}."""
    plan = strip_notes(plan_with_notes)
    direct = [z for z, v in plan["zones"].items() if v["egress"] == "direct"]
    internal = [z for z in plan["zones"] if z not in direct]
    files = {
        "etc/network/interfaces": _interfaces(plan),
        "etc/nftables.conf": _nftables(plan, model),
        "etc/sysctl.d/90-nullbill.conf": HEADER + "net.ipv4.ip_forward = 1\n",
        "etc/systemd/system/nullbill-dnsmasq@.service": DNSMASQ_UNIT,
        "etc/nullbill/dnsmasq-external.conf": _dnsmasq(plan, model, direct, external=True),
        "etc/nullbill/dnsmasq-internal.conf": _dnsmasq(plan, model, internal, external=False),
        **_links(plan, model),
    }
    return files
