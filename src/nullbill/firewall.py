"""pve-firewall files from the plan: default deny in and out on every vNIC.

Reference: https://pve.proxmox.com/pve-docs/chapter-pve-firewall.html

Endpoints enforce every flow: the destination accepts it IN and each source
accepts it OUT, so traffic inside a zone is filtered as well as traffic the
router forwards. The router itself is left open on its vNICs; its own
nftables rules are its guard.
"""

from nullbill.flows import HOST, HOST_SET, PRIVATE, TAILSCALE_PORT, addresses, from_people, resolve_flows, svc_set
from nullbill.render import strip_notes

HEADER = "# Generated by nullbill. Do not edit; change config.yaml and re-run apply.\n"


def _group(guest: dict) -> str:
    # Security group names are short in pve-firewall; the template VMID is unique.
    return f"nbp-{guest['template_vmid']}"


class _Rules:
    """IN rules per destination guest and OUT rules per source guest."""

    def __init__(self, plan: dict, model: dict) -> None:
        self.inbound: dict[str, list[str]] = {name: [] for name in plan["guests"]}
        self.outbound: dict[str, list[str]] = {name: [] for name in plan["guests"]}
        self.host: list[str] = []
        for flow in resolve_flows(plan, model):
            match = f"-p {flow.proto} -dport {flow.port}"
            if flow.dest == HOST:
                # The host admits the VPN through the management ipset, which
                # opens every PVE management port; any other source gets only
                # its own port in host.fw.
                if not from_people(flow.ref):
                    self._add(self.host, f"IN ACCEPT -source +{flow.source_set} {match}", flow.ref)
                dest, label = flow.dest_cidrs[0], "the PVE host"
            else:
                self._add(self.inbound[flow.dest], f"IN ACCEPT -source +{flow.source_set} {match}", flow.ref)
                dest, label = f"+{svc_set(flow.dest)}", flow.dest
            for src in flow.sources:
                if src not in (flow.dest, "router"):
                    self._add(self.outbound[src], f"OUT ACCEPT -dest {dest} {match}", f"to {label}")

    @staticmethod
    def _add(rules: list[str], rule: str, comment: str) -> None:
        # Roles all arrive from the vpn address, so two roles can yield one rule.
        if not any(r.startswith(rule + " #") for r in rules):
            rules.append(f"{rule} # {comment}")


def _ipset(name: str, entries: list[str]) -> str:
    return f"[IPSET {name}]\n" + "".join(f"{e}\n" for e in entries) + "\n"


def _cluster(plan: dict, lan_open: bool) -> str:
    sets = [
        _ipset("nb-zones", [plan["network_base"]]),
        _ipset("nb-private", list(PRIVATE)),
        _ipset(HOST_SET, [plan["zones"]["mgmt"]["host_ip"]]),
        *(_ipset(f"nb-zone-{z}", [v["subnet"]]) for z, v in plan["zones"].items()),
        *(_ipset(svc_set(g), addresses(v)) for g, v in plan["guests"].items()),
    ]
    # The owner reaches the web UI and SSH over the VPN in both variants.
    vpn = plan["guests"]["vpn"]["ip"]
    sets.append(_ipset("management", [vpn]))
    aliases = ""
    if not lan_open:
        # PVE adds the local_network alias to the management ipset whatever
        # the ipset holds, and detects it as the host's LAN unless the alias
        # is set; so closed, it is set to the vpn guest too.
        aliases = f"[ALIASES]\nlocal_network {vpn} # not the LAN: PVE adds it to management\n\n"
    note = (
        "# LAN variant for the first apply: PVE's local_network (the LAN) is in its\n"
        "# management ipset, so 8006 and 22 stay open to it until VPN reach is confirmed.\n"
        if lan_open
        else ""
    )
    return HEADER + note + "[OPTIONS]\nenable: 1\npolicy_in: DROP\npolicy_out: ACCEPT\n\n" + aliases + "".join(sets)


def _guest_rules(name: str, rules_by_guest: _Rules, egress: str) -> list[str]:
    rules = rules_by_guest.inbound[name] + rules_by_guest.outbound[name]
    if name == "vpn":
        # Tailscale's direct path to devices on the home network; NullBill's
        # own zones stay reachable through flows only.
        rules += [
            "OUT DROP -dest +nb-zones # NullBill's zones only through flows",
            f"OUT ACCEPT -dest +nb-private -p udp -sport {TAILSCALE_PORT} # Tailscale, direct to devices at home",
        ]
    if egress == "direct":
        rules += ["OUT DROP -dest +nb-private # no LAN or other private ranges", "OUT ACCEPT # internet via the router"]
    return rules


def _guest_file(name: str, guest: dict, rules: list[str]) -> str:
    if name == "router":
        note = "# The router forwards for every zone; its nftables ruleset filters.\n"
        return HEADER + note + "[OPTIONS]\nenable: 1\npolicy_in: ACCEPT\npolicy_out: ACCEPT\n"
    # install.sh gives the nullbill container its LAN leg as net0 (no PVE
    # firewall); its mgmt leg, which apply adds, is net1.
    nic = "net1" if guest.get("installed") else "net0"
    filter_set = _ipset(f"ipfilter-{nic}", addresses(guest))
    body = HEADER + "[OPTIONS]\nenable: 1\nipfilter: 1\npolicy_in: DROP\npolicy_out: DROP\n\n" + filter_set + "[RULES]\n"
    return body + "".join(f"{r}\n" for r in rules)


def render_firewall(plan_with_notes: dict, model: dict) -> dict[str, str]:
    """Return {relative path: content}: host.fw for /etc/pve/local (the
    node's own file), the rest for /etc/pve/firewall."""
    plan = strip_notes(plan_with_notes)
    plan["network_base"] = model["network"]["base"]
    by_guest = _Rules(plan, model)
    files = {
        "cluster.fw": _cluster(plan, lan_open=False),
        "cluster-lan-open.fw": _cluster(plan, lan_open=True),
        "host.fw": (
            HEADER
            + "# The VPN reaches the host through the management ipset in cluster.fw.\n[OPTIONS]\nenable: 1\n"
            + ("\n[RULES]\n" + "".join(f"{r}\n" for r in by_guest.host) if by_guest.host else "")
        ),
    }
    groups = []
    for name, guest in plan["guests"].items():
        rules = _guest_rules(name, by_guest, plan["zones"][guest["zone"]]["egress"])
        if guest["kind"] == "vm-pool":
            # Clones copy the template's firewall file, which points at this group.
            group = _group(guest)
            groups.append(f"[group {group}] # {name} clones\n" + "".join(f"{r}\n" for r in rules) + "\n")
            files[f"{guest['template_vmid']}.fw"] = _guest_file(name, guest, [f"GROUP {group}"])
        else:
            files[f"{guest['vmid']}.fw"] = _guest_file(name, guest, rules)
    files["cluster.fw"] += "".join(groups)
    files["cluster-lan-open.fw"] += "".join(groups)
    return files
