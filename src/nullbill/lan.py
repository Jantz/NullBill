"""Closing the home network (LAN) to Proxmox's web UI and SSH, safely (#9).

Until the owner closes it, the LAN keeps PVE's default access to 8006 and
22 (firewall.py's cluster-lan-open.fw). Closing installs the cluster.fw
whose management ipset holds only the vpn guest, but first arms a timer on
the host that puts the open file back after REVERT_AFTER_S. The owner
cancels it by pressing "Keep it closed" on the page, which the page accepts
only from the vpn guest's address: the press itself shows the tailnet
reaches NullBill. A wrong policy therefore locks nobody out for longer than
the timer, and a restart of the host before the press opens it again at
boot (boot_unit).

The state lives on the controller in $NULLBILL_HOME/lan.json:
open (the default), closing (the timer is armed) or closed. While it is
closing or closed, the controller reaches the host at its mgmt address,
which the closed firewall still admits, and the page refuses requests from
outside the NullBill network once it is closed.

The timer runs on the host and tells nobody: a close that was never
confirmed stays "closing" in lan.json after the host opened the LAN again.
Past the deadline the record is therefore only a guess, and whoever reads it
then (the page, verify, apply's host stage) asks the host whether the timer
is still there (settle) and writes down what it found, with when the close
ran out.
"""

import ipaddress
import json
import time
from collections.abc import Callable
from pathlib import Path

FILE = "lan.json"
OPEN, CLOSING, CLOSED = "open", "closing", "closed"
REVERT_UNIT = "nb-lan-revert"
REVERT_AFTER_S = 15 * 60
# The open cluster.fw, kept on the host's own disk for the timer to restore.
SAVED_OPEN = "/root/nullbill/cluster-lan-open.fw"
CLUSTER_FW = "/etc/pve/firewall/cluster.fw"
# On the host's disk while a close waits for "Keep it closed". The timer is
# gone after a reboot; BOOT_UNIT then opens the LAN again at boot.
MARKER = "/root/nullbill/lan-closing"
BOOT_UNIT = "nb-lan-revert-boot.service"
REOPEN = f"/bin/cp {SAVED_OPEN} {CLUSTER_FW} && /bin/rm -f {MARKER}"


def read(home: Path) -> dict:
    path = home / FILE
    if not path.exists():
        return {"state": OPEN}
    return json.loads(path.read_text())


def write(home: Path, state: str, deadline: float | None = None, lapsed: float | None = None) -> None:
    """lapsed: when a close that nobody confirmed ran out, kept with the
    open state it left behind until the next close."""
    data = {"state": state} | ({"deadline": deadline} if deadline is not None else {})
    data |= {"lapsed": lapsed} if lapsed is not None else {}
    path = home / FILE
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(data) + "\n")
    tmp.replace(path)


def state(home: Path) -> str:
    return read(home)["state"]


def arm_command() -> str:
    """Start the timer that restores the open file, and leave the marker
    that makes BOOT_UNIT restore it if the host restarts first; a timer
    left from an earlier close is replaced."""
    return (
        f"systemctl stop {REVERT_UNIT}.timer {REVERT_UNIT}.service 2>/dev/null; "
        f"systemctl reset-failed {REVERT_UNIT}.service 2>/dev/null; "
        f"touch {MARKER} && "
        f"systemd-run --quiet --unit={REVERT_UNIT} --on-active={REVERT_AFTER_S} --timer-property=AccuracySec=5s "
        f"/bin/sh -c '{REOPEN}'"
    )


def boot_unit() -> str:
    """Opens the LAN again at boot when a close was never confirmed: the
    transient timer does not survive a restart, the closed cluster.fw does.
    It needs /etc/pve, which pve-cluster mounts."""
    return (
        "# Generated by nullbill (lan.py). Do not edit.\n"
        "[Unit]\n"
        "Description=NullBill: open Proxmox to the home network again after a restart during an unconfirmed close\n"
        f"ConditionPathExists={MARKER}\n"
        "Requires=pve-cluster.service\nAfter=pve-cluster.service\nBefore=pve-firewall.service\n\n"
        f"[Service]\nType=oneshot\nExecStart=/bin/sh -c '{REOPEN}'\n\n"
        "[Install]\nWantedBy=multi-user.target\n"
    )


ARMED = f"systemctl is-active --quiet {REVERT_UNIT}.timer && echo armed || echo gone"
# The marker goes first: a timer that fires meanwhile still reopens.
DISARM = f"rm -f {MARKER} && systemctl stop {REVERT_UNIT}.timer"


def deadline(now: float | None = None) -> float:
    return (now if now is not None else time.time()) + REVERT_AFTER_S


# The timer fires within seconds of the deadline (AccuracySec=5s in arm_command).
GRACE_S = 20


def overdue(home: Path, now: float | None = None) -> bool:
    """A close whose deadline has passed: the host has opened the LAN again
    by now, or should have. Only the host knows which."""
    found = read(home)
    at = found.get("deadline")
    return found["state"] == CLOSING and at is not None and (now if now is not None else time.time()) > at + GRACE_S


def settle(home: Path, ask: Callable[[str], str]) -> str:
    """The state, after asking the host about a close that is overdue: with
    the timer gone the LAN is open again, and the record says so and since
    when. `ask` runs a command on the host and returns what it printed."""
    found = read(home)
    if overdue(home) and ask(ARMED).strip() == "gone":
        write(home, OPEN, lapsed=found["deadline"])
        return OPEN
    return found["state"]


def inside(address: str, base: str) -> bool:
    """Whether a client address is in the NullBill network: the vpn guest,
    the on-site screen through the host's mgmt address, or a guest."""
    try:
        ip = ipaddress.ip_address(address.removeprefix("::ffff:"))
    except ValueError:
        return False
    return ip in ipaddress.ip_network(base)
