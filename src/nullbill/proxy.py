"""egress-proxy files: a Squid allow-list for zones with egress: proxy.

Guests in those zones have no route to the internet; pve-firewall and the
router let them reach only this proxy. Squid then forwards HTTP and HTTPS
CONNECT to the catalog's allow-listed names and refuses everything else.
"""

from nullbill.flows import PRIVATE, resolve_flows
from nullbill.model import NODE_EXPORTER
from nullbill.render import strip_notes

HEADER = "# Generated by nullbill. Do not edit; change config.yaml and re-run apply.\n"
PROXY = "egress-proxy"


def allows(allow: list[str], name: str) -> bool:
    """Whether Squid's dstdomain list admits name: .x matches x and its subdomains."""
    return any(name == d[1:] or name.endswith(d) if d.startswith(".") else name == d for d in allow)


def proxy_port(model: dict) -> int:
    """Squid's port: the proxy's one TCP port other than node_exporter's."""
    (port,) = (p["port"] for p in model["services"][PROXY]["ports"] if p != NODE_EXPORTER)
    return port


def _clients(plan: dict, model: dict) -> list[str]:
    port = proxy_port(model)
    cidrs = {c for f in resolve_flows(plan, model) if f.dest == PROXY and f.port == port for c in f.source_cidrs}
    return sorted(cidrs)


def _own_lists(plan: dict, model: dict) -> list[str]:
    """One acl pair per guest with a proxy_allow of its own, such as the
    operator's model API, so other guests in its zone cannot use it."""
    lines = []
    for name, svc in model["services"].items():
        if svc.get("proxy_allow") and name in plan["guests"]:
            lines += [
                f"acl from_{name} src {plan['guests'][name]['ip']}/32\n",
                f"acl allowed_{name} dstdomain -n {' '.join(svc['proxy_allow'])}\n",
                f"http_access allow from_{name} allowed_{name}\n",
            ]
    return lines


def render_proxy(plan_with_notes: dict, model: dict) -> dict[str, str]:
    """Return {path on egress-proxy: content}; empty when it is not planned."""
    plan = strip_notes(plan_with_notes)
    if PROXY not in plan["guests"]:
        return {}
    port = proxy_port(model)
    lines = [
        HEADER,
        f"http_port {plan['guests'][PROXY]['ip']}:{port}\n\n",
        f"acl clients src {' '.join(_clients(plan, model))}\n",
        f"acl private dst {' '.join(PRIVATE)}\n",
        "acl SSL_ports port 443\n",
        "acl Safe_ports port 80 443\n",
        "acl CONNECT method CONNECT\n",
        "# -n: match the requested name only, so a bare IP never matches by reverse DNS.\n",
        "acl allowed dstdomain -n " + " ".join(model["proxy"]["allow"]) + "\n\n",
        "http_access deny !clients\n",
        "http_access deny !Safe_ports\n",
        "http_access deny CONNECT !SSL_ports\n",
        "http_access deny private\n",
        "http_access allow allowed\n",
        *_own_lists(plan, model),
        "http_access deny all\n\n",
        "# Forward only: keep nothing and drop the client address header.\n",
        "cache deny all\n",
        "forwarded_for delete\n",
        "httpd_suppress_version_string on\n",
    ]
    return {"etc/squid/squid.conf": "".join(lines)}
